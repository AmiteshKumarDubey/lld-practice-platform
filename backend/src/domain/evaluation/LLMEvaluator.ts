/**
 * Domain Evaluator: LLMEvaluator
 * LLM-driven qualitative evaluator with automatic fallback to MockLLMEvaluator.
 */

import { IEvaluator, EvaluationResultPartial } from './IEvaluator';
import { MockLLMEvaluator } from './MockLLMEvaluator';
import { Submission } from '../models/Submission';
import { RubricCriteria } from '../models/Problem';

export class LLMEvaluator implements IEvaluator {
  readonly name = 'LLMEvaluator';
  private fallbackEvaluator = new MockLLMEvaluator();

  async evaluate(submission: Submission, rubric: RubricCriteria): Promise<EvaluationResultPartial> {
    const apiKey = process.env.OPENAI_API_KEY || process.env.CLAUDE_API_KEY;

    if (!apiKey) {
      // Fallback to MockLLMEvaluator if no API key configured
      return this.fallbackEvaluator.evaluate(submission, rubric);
    }

    try {
      // If API key is present, execute API call with timeout resilience
      const result = await this.callLLMApi(apiKey, submission, rubric);
      return result;
    } catch (error) {
      console.warn('LLM API call failed or timed out. Falling back to MockLLMEvaluator:', error);
      const fallbackResult = await this.fallbackEvaluator.evaluate(submission, rubric);
      fallbackResult.summary = `(Offline Fallback Evaluator Used) ${fallbackResult.summary}`;
      return fallbackResult;
    }
  }

  private async callLLMApi(apiKey: string, submission: Submission, rubric: RubricCriteria): Promise<EvaluationResultPartial> {
    // Controller timeout of 6 seconds to ensure swift response
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);

    try {
      const prompt = `You are a Senior Principal Software Architect evaluating a Low-Level Design (LLD) candidate submission.
Format: ${submission.format}
Problem Rubric:
- Expected Patterns: ${rubric.recommendedPatterns.join(', ')}
- Design Goals: ${rubric.keyDesignGoals.join(', ')}

Candidate Submission Code/Text:
\`\`\`
${submission.content}
\`\`\`

Return a JSON object with:
{
  "qualitativeScore": number (0 to 100),
  "summary": "2-3 sentences overview",
  "strengths": ["bullet point 1", "bullet point 2"],
  "weaknesses": ["weakness 1", "weakness 2"],
  "improvementSuggestions": ["actionable advice 1", "actionable advice 2"],
  "recommendedPatterns": ["Pattern 1", "Pattern 2"]
}`;

      // Example standard fetch to OpenAI API
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${apiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-3.5-turbo',
          messages: [{ role: 'user', content: prompt }],
          temperature: 0.2,
          response_format: { type: 'json_object' }
        }),
        signal: controller.signal
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        throw new Error(`OpenAI API responded with status ${response.status}`);
      }

      const data = (await response.json()) as any;
      const contentStr = data.choices[0]?.message?.content;
      const parsed = JSON.parse(contentStr);

      return {
        qualitativeScore: parsed.qualitativeScore || 80,
        summary: parsed.summary || 'Qualitative feedback generated by OpenAI LLM evaluator.',
        strengths: parsed.strengths || [],
        weaknesses: parsed.weaknesses || [],
        improvementSuggestions: parsed.improvementSuggestions || [],
        recommendedPatterns: parsed.recommendedPatterns || rubric.recommendedPatterns
      };
    } catch (err) {
      clearTimeout(timeoutId);
      throw err;
    }
  }
}
